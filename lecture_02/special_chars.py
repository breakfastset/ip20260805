# special characters:
# \"   - escape double quote
# \'   - escape single quote
# \n   - new line
# \t   - tab
# \\   - escape backslash
# \b   - backspace

print("double quote: \"")
print("single quote: \'")
print("new line: (\n)")  # print ) on the next line
print("tab: in\t\tbetween")  # 2 tabs
print("backslash: \\")
print("backspace: abcd\b\befg")  # abefg, deletes c and d

# This is the newline character : \n
print("This is the newline character: \\n")


