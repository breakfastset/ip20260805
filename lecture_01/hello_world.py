print("Hello,,,, World")
# this is a comment
# comments are not interpreted
# comments are for documentation

# Python is
# 1. case-sensitive
# 2. space sensitive
print("One")   # default print() will end with newline
print("Two", end="++++")
print("Three", end="")   # end is not a newline
print("Four")

print()

# She says "I'll be here tomorrow."
print("She says \"I'll be here tomorrow.\" ")
# \" means to escape the " (double quote)
#    to print the character " instead of interpreting
#    it as the end of the string
#
# special characters:
# \"   - escape double quote
# \'   - escape single quote
# \n   - new line
# \t   - tab
# \\   - escape backslash
# \b   - backspace




